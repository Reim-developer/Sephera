//! End-to-end behaviour of `sephera schema-impact` over real git
//! repositories.
//!
//! These drive the real binary, because the claim is about which
//! side a comparison is built from — the old side from a worktree
//! checkout, the new side from the working tree or a second
//! checkout — and any reading faked would make the claim
//! meaningless. JSON assertions compare parsed values, never
//! bytes: key order in the output is alphabetical by construction,
//! not a contract.

use std::path::Path;
use std::process::{Command, Output};

use tempfile::tempdir;

fn write_file(base_dir: &Path, relative_path: &str, contents: &[u8]) {
    let absolute_path = base_dir.join(relative_path);
    if let Some(parent) = absolute_path.parent() {
        std::fs::create_dir_all(parent).unwrap();
    }
    std::fs::write(absolute_path, contents).unwrap();
}

fn git(dir: &Path, args: &[&str]) {
    let output = Command::new("git")
        .args(args)
        .current_dir(dir)
        .env("GIT_AUTHOR_NAME", "Test")
        .env("GIT_AUTHOR_EMAIL", "test@example.com")
        .env("GIT_COMMITTER_NAME", "Test")
        .env("GIT_COMMITTER_EMAIL", "test@example.com")
        .output()
        .unwrap();
    assert!(output.status.success(), "{output:?}");
}

fn commit_all(dir: &Path, message: &str) {
    git(dir, &["add", "."]);
    git(dir, &["commit", "-qm", message]);
}

const OLD_PROTO: &[u8] = b"syntax = \"proto3\";\npackage api;\nmessage User {\n  string name = 1;\n  int32 age = 2;\n}\n";

const NEW_PROTO_NAME_REMOVED: &[u8] =
    b"syntax = \"proto3\";\npackage api;\nmessage User {\n  int32 age = 2;\n}\n";

const NEW_PROTO_NAME_RENAMED: &[u8] = b"syntax = \"proto3\";\npackage api;\nmessage User {\n  string full_name = 1;\n  int32 age = 2;\n}\n";

const PY_GEN: &[u8] =
    b"# Generated by the protocol buffer compiler.  DO NOT EDIT!\n";

const PY_CONSUMER: &[u8] = b"from api.user_pb2 import User\n\n\ndef make():\n    return User(name=\"Ada\", age=36)\n";

/// A repo whose working tree removes `name` from `User` while the
/// consumer still constructs with it: the removal the report must
/// join to a proven consumer.
fn repo_with_removal() -> tempfile::TempDir {
    let temp_dir = tempdir().unwrap();
    let dir = temp_dir.path();
    git(dir, &["init", "-q"]);
    write_file(dir, "api/user.proto", OLD_PROTO);
    write_file(dir, "api/user_pb2.py", PY_GEN);
    write_file(dir, "consumer.py", PY_CONSUMER);
    commit_all(dir, "v1");
    git(dir, &["tag", "v1"]);
    write_file(dir, "api/user.proto", NEW_PROTO_NAME_REMOVED);
    temp_dir
}

fn run_schema_impact(dir: &Path, extra_args: &[&str]) -> Output {
    let mut command = Command::new(env!("CARGO_BIN_EXE_sephera"));
    command
        .arg("schema-impact")
        .arg("--path")
        .arg(dir)
        .arg("--from")
        .arg("v1")
        .args(extra_args);
    command.output().unwrap()
}

fn stdout(output: &Output) -> String {
    String::from_utf8(output.stdout.clone()).unwrap()
}

fn stderr(output: &Output) -> String {
    String::from_utf8(output.stderr.clone()).unwrap()
}

#[test]
fn field_removed_with_python_consumer_markdown() {
    let repo = repo_with_removal();
    let output = run_schema_impact(repo.path(), &[]);
    assert!(output.status.success(), "{}", stderr(&output));
    let text = stdout(&output);
    assert!(text.contains("api.User.name"), "{text}");
    assert!(text.contains("removed"), "{text}");
    assert!(text.contains("consumer.py"), "{text}");
    assert!(text.contains("constructor keyword"), "{text}");
    assert!(text.contains("Proven consumers"), "{text}");
}

#[test]
fn field_removed_json_shape_and_fail_on() {
    let repo = repo_with_removal();
    let output =
        run_schema_impact(repo.path(), &["--format", "json"]);
    assert!(output.status.success(), "{}", stderr(&output));
    let parsed: serde_json::Value =
        serde_json::from_slice(&output.stdout).unwrap();
    assert_eq!(parsed["from_ref"], "v1");
    assert_eq!(parsed["to_ref"], "working tree");
    let breaks = parsed["breaks"].as_array().unwrap();
    assert_eq!(breaks.len(), 1, "{parsed}");
    assert_eq!(breaks[0]["element"], "api.User.name");
    assert_eq!(breaks[0]["change"], "removed");
    let proven = breaks[0]["proven"].as_array().unwrap();
    assert_eq!(proven.len(), 1, "{parsed}");
    assert_eq!(proven[0]["file"], "consumer.py");
    assert_eq!(proven[0]["via"], "constructor_kwarg");
    assert!(breaks[0]["named"].as_array().unwrap().is_empty());

    // One proven break: --fail-on 1 fails the run, --fail-on 2
    // does not. The report is still printed either way.
    let failing = run_schema_impact(repo.path(), &["--fail-on", "1"]);
    assert_eq!(failing.status.code(), Some(2), "{}", stderr(&failing));
    let passing = run_schema_impact(repo.path(), &["--fail-on", "2"]);
    assert!(passing.status.success(), "{}", stderr(&passing));
}

#[test]
fn rename_reports_old_name_and_new_name() {
    let temp_dir = tempdir().unwrap();
    let dir = temp_dir.path();
    git(dir, &["init", "-q"]);
    write_file(dir, "api/user.proto", OLD_PROTO);
    write_file(dir, "api/user_pb2.py", PY_GEN);
    write_file(dir, "consumer.py", PY_CONSUMER);
    commit_all(dir, "v1");
    git(dir, &["tag", "v1"]);
    write_file(dir, "api/user.proto", NEW_PROTO_NAME_RENAMED);
    let output = run_schema_impact(dir, &["--format", "json"]);
    assert!(output.status.success(), "{}", stderr(&output));
    let parsed: serde_json::Value =
        serde_json::from_slice(&output.stdout).unwrap();
    let breaks = parsed["breaks"].as_array().unwrap();
    assert_eq!(breaks.len(), 1, "{parsed}");
    assert_eq!(breaks[0]["element"], "api.User.name");
    assert_eq!(
        breaks[0]["change"],
        serde_json::json!({"renamed": {"from": "name", "to": "full_name"}}),
        "{parsed}"
    );
    assert_eq!(breaks[0]["proven"][0]["file"], "consumer.py");
}

#[test]
fn named_only_never_fails_the_gate() {
    let temp_dir = tempdir().unwrap();
    let dir = temp_dir.path();
    git(dir, &["init", "-q"]);
    write_file(dir, "api/user.proto", OLD_PROTO);
    write_file(dir, "api/user_pb2.py", PY_GEN);
    write_file(
        dir,
        "consumer.py",
        b"import api.user_pb2\n\n\ndef get(data):\n    return data[\"name\"]\n",
    );
    commit_all(dir, "v1");
    git(dir, &["tag", "v1"]);
    write_file(dir, "api/user.proto", NEW_PROTO_NAME_REMOVED);
    // The JSON key is name-match evidence only: the break is real
    // but --fail-on must not fire on it.
    let output = run_schema_impact(dir, &["--format", "json", "--fail-on", "1"]);
    assert!(output.status.success(), "{}", stderr(&output));
    let parsed: serde_json::Value =
        serde_json::from_slice(&output.stdout).unwrap();
    let breaks = parsed["breaks"].as_array().unwrap();
    assert_eq!(breaks.len(), 1, "{parsed}");
    assert!(breaks[0]["proven"].as_array().unwrap().is_empty());
    assert_eq!(breaks[0]["named"][0]["via"], "json_key");
}

#[test]
fn to_ref_compares_two_checkouts() {
    let temp_dir = tempdir().unwrap();
    let dir = temp_dir.path();
    git(dir, &["init", "-q"]);
    write_file(dir, "api/user.proto", OLD_PROTO);
    write_file(dir, "api/user_pb2.py", PY_GEN);
    write_file(dir, "consumer.py", PY_CONSUMER);
    commit_all(dir, "v1");
    git(dir, &["tag", "v1"]);
    write_file(dir, "api/user.proto", NEW_PROTO_NAME_REMOVED);
    commit_all(dir, "v2");
    git(dir, &["tag", "v2"]);
    let output = run_schema_impact(dir, &["--to", "v2", "--format", "json"]);
    assert!(output.status.success(), "{}", stderr(&output));
    let parsed: serde_json::Value =
        serde_json::from_slice(&output.stdout).unwrap();
    assert_eq!(parsed["to_ref"], "v2");
    assert_eq!(parsed["breaks"][0]["element"], "api.User.name");
    assert_eq!(parsed["breaks"][0]["proven"][0]["file"], "consumer.py");
}

#[test]
fn non_repo_is_an_error_not_an_empty_report() {
    let temp_dir = tempdir().unwrap();
    let output = run_schema_impact(temp_dir.path(), &[]);
    assert!(!output.status.success());
    assert!(stderr(&output).contains("git repository"), "{}", stderr(&output));
}

#[test]
fn url_is_refused() {
    let repo = repo_with_removal();
    let mut command = Command::new(env!("CARGO_BIN_EXE_sephera"));
    command
        .arg("schema-impact")
        .arg("--url")
        .arg("https://example.com/repo.git")
        .arg("--from")
        .arg("v1");
    let _ = repo;
    let output = command.output().unwrap();
    assert!(!output.status.success());
    assert!(stderr(&output).contains("--url"), "{}", stderr(&output));
}

#[test]
fn proto2_is_an_error() {
    let temp_dir = tempdir().unwrap();
    let dir = temp_dir.path();
    git(dir, &["init", "-q"]);
    write_file(
        dir,
        "api/user.proto",
        b"syntax = \"proto2\";\npackage api;\nmessage User {\n  required string name = 1;\n}\n",
    );
    commit_all(dir, "v1");
    git(dir, &["tag", "v1"]);
    let output = run_schema_impact(dir, &[]);
    assert!(!output.status.success());
    assert!(stderr(&output).contains("proto2"), "{}", stderr(&output));
}

/// A scoped run reports the break that lives inside the scope,
/// scope-relative, while a consumer outside the scope is correctly
/// absent — the break is not hidden, and the out-of-scope file is
/// not claimed. This pins the scope rule the adversarial battery
/// verified by hand: scope restricts both sides, it does not
/// erase in-scope breaks.
#[test]
fn scoped_run_reports_in_scope_break_without_out_of_scope_consumer() {
    let temp_dir = repo_with_removal();
    let dir = temp_dir.path();
    let output = Command::new(env!("CARGO_BIN_EXE_sephera"))
        .arg("schema-impact")
        .arg("--path")
        .arg(dir.join("api"))
        .arg("--from")
        .arg("v1")
        .output()
        .unwrap();
    assert!(output.status.success(), "{}", stderr(&output));
    let text = stdout(&output);
    assert!(text.contains("api.User.name"), "{text}");
    assert!(text.contains("Schema file: `user.proto`"), "{text}");
    assert!(text.contains("No proven consumers"), "{text}");
    assert!(!text.contains("consumer.py"), "{text}");
}

